def _skyswitch_telco_doc_capabilities() -> list[dict[str, Any]]:
    capabilities: list[dict[str, Any]] = []
    seen: set[str] = set()
    for section, title, method, endpoint, scopes, doc_url, description in SKYSWITCH_TELCO_DOC_TOOL_ENTRIES:
        section_slug = _slugify(section)
        title_slug = _slugify(title)
        capability_id = f"telco-{section_slug}-{title_slug}"
        if capability_id in seen:
            capability_id = f"{capability_id}-{_slugify(method)}"
        seen.add(capability_id)
        risk = _skyswitch_telco_risk(method=method, title=title)
        guardrail = "read_only_test_only"
        if risk == "destructive-confirmed":
            guardrail = "destructive_action_requires_explicit_confirmation_and_readback"
        elif risk == "write-requested":
            guardrail = "write_action_requires_explicit_confirmation_and_readback"
        capabilities.append(
            {
                "id": capability_id,
                "title": f"SkySwitch {title}",
                "file": f"telco-skyswitch-{capability_id.removeprefix('telco-')}.md",
                "risk": risk,
                "tools": [f"skyswitch_telco_{title_slug.replace('-', '_')}"],
                "doc_section": section,
                "doc_operation": title,
                "doc_url": doc_url.removesuffix('.md'),
                "description": description,
                "api_surface": "skyswitch-telco",
                "api_base_hint": SKYSWITCH_TELCO_API_BASE_URL,
                "portal_url": SKYSWITCH_TELCO_DOCS_URL,
                "endpoint": endpoint,
                "http_method": method,
                "api_object": section_slug,
                "api_action": title_slug,
                "api_scope": scopes,
                "read_only_test": True,
                "guardrail": guardrail,
            }
        )
    return capabilities


def _skyswitch_telco_risk(*, method: str, title: str) -> str:
    normalized_title = title.strip().lower()
    if method == "GET" or normalized_title.startswith(("get ", "list ", "validate ", "check ", "calculate ")):
        return "read"
    if method == "DELETE":
        return "destructive-confirmed"
    return "write-requested"


def _netsapiens_doc_capabilities() -> list[dict[str, Any]]:
    capabilities: list[dict[str, Any]] = []
    for group in NETSAPIENS_DOC_TOOL_GROUPS:
        section_slug = _slugify(str(group["section"]))
        api_object = str(group["object"])
        for operation in group["operations"]:
            slug, title, risk, action, tool_name, *method_override = operation
            method = str(method_override[0]) if method_override else "post"
